    public List<SeasonRankingEntry> getSeasonRanking(
            int seasonId,
            String category,
            int limit
    ) throws SQLException {

        checkConnection();

        String column;

        switch (category.toLowerCase(java.util.Locale.ROOT)) {
            case "kills":
                column = "kills";
                break;

            case "ores_mined":
                column = "ores_mined";
                break;

            case "active_seconds":
                column = "active_seconds";
                break;

            default:
                throw new IllegalArgumentException(
                        "Categoría de temporada no válida: " + category
                );
        }

        if (limit < 1) {
            throw new IllegalArgumentException(
                    "El límite del ranking debe ser mayor que cero."
            );
        }

        String sql =
                "SELECT ss.uuid, " +
                        "COALESCE(ps.name, ss.uuid) AS player_name, " +
                        "ss." + column + " AS score " +
                        "FROM season_stats ss " +
                        "LEFT JOIN player_stats ps ON ps.uuid = ss.uuid " +
                        "WHERE ss.season_id = ? " +
                        "ORDER BY ss." + column + " DESC, ss.uuid ASC " +
                        "LIMIT ?";

        List<SeasonRankingEntry> ranking = new ArrayList<>();

        try (java.sql.PreparedStatement statement =
                     getConnection().prepareStatement(sql)) {

            statement.setInt(1, seasonId);
            statement.setInt(2, limit);

            try (java.sql.ResultSet result = statement.executeQuery()) {
                while (result.next()) {
                    ranking.add(new SeasonRankingEntry(
                            result.getString("uuid"),
                            result.getString("player_name"),
                            result.getLong("score")
                    ));
                }
            }
        }

        return ranking;
    }

    /**
     * Comprueba si una kill puede sumar estadísticas.
     *
     * El bloqueo es independiente para cada dirección:
     * A -> B no bloquea B -> A.
     *
     * @return 0 si la kill puede puntuar;
     *         milisegundos restantes si está bloqueada.
     */
    public synchronized long tryRegisterKillPair(
            Player killer,
            Player victim,
            long now,
            long cooldownMillis
    ) throws SQLException {

        checkConnection();

        if (killer == null || victim == null
                || killer.getUniqueId().equals(victim.getUniqueId())) {
            return cooldownMillis;
        }

        if (cooldownMillis <= 0L) {
            throw new IllegalArgumentException(
                    "El tiempo de espera debe ser positivo."
            );
        }

        String killerUuid = killer.getUniqueId().toString();
        String victimUuid = victim.getUniqueId().toString();

        String selectSql =
                "SELECT last_kill_at FROM kill_antifarm_player_targets "
                        + "WHERE killer_uuid = ? AND victim_uuid = ?";

        try (PreparedStatement select =
                     connection.prepareStatement(selectSql)) {

            select.setString(1, killerUuid);
            select.setString(2, victimUuid);

            try (ResultSet result = select.executeQuery()) {

                if (result.next()) {
                    long lastKillAt = result.getLong("last_kill_at");
                    long elapsed = now - lastKillAt;

                    if (elapsed < 0L) {
                        return cooldownMillis;
                    }

                    if (elapsed < cooldownMillis) {
                        return cooldownMillis - elapsed;
                    }

                    // El bloqueo terminó: esta kill vuelve a puntuar.
                    String updateSql =
                            "UPDATE kill_antifarm_player_targets "
                                    + "SET last_kill_at = ? "
                                    + "WHERE killer_uuid = ? "
                                    + "AND victim_uuid = ?";

                    try (PreparedStatement update =
                                 connection.prepareStatement(updateSql)) {

                        update.setLong(1, now);
                        update.setString(2, killerUuid);
                        update.setString(3, victimUuid);
                        update.executeUpdate();
                    }

                    return 0L;
                }
            }
        }

        // Primera kill puntuable de este asesino contra esta víctima.
        String insertSql =
                "INSERT INTO kill_antifarm_player_targets "
                        + "(killer_uuid, victim_uuid, last_kill_at) "
                        + "VALUES (?, ?, ?)";

        try (PreparedStatement insert =
                     connection.prepareStatement(insertSql)) {

            insert.setString(1, killerUuid);
            insert.setString(2, victimUuid);
            insert.setLong(3, now);
            insert.executeUpdate();
        }

        return 0L;
    }

