package org.brunojaegerk.deluxestats.database;

import cn.nukkit.Player;
import org.brunojaegerk.deluxestats.DeluxeStats;

import java.io.File;
import java.sql.Connection;
import java.sql.Driver;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Properties;
import java.util.ArrayList;
import java.util.List;

public class DatabaseManager {

    private final DeluxeStats plugin;
    private Connection connection;

    public DatabaseManager(DeluxeStats plugin) {
        this.plugin = plugin;
    }

    public synchronized void open() throws SQLException {
        if (connection != null && !connection.isClosed()) {
            return;
        }

        File folder = plugin.getDataFolder();

        if (!folder.exists() && !folder.mkdirs()) {
            throw new SQLException(
                    "No se pudo crear la carpeta de datos: "
                            + folder.getAbsolutePath()
            );
        }

        File databaseFile = new File(folder, "deluxestats");
        String databasePath = databaseFile.getAbsolutePath()
                .replace('\\', '/');
        String url = "jdbc:h2:file:" + databasePath;

        try {
            String driverName =
                    "org.brunojaegerk.deluxestats.libs.h2.Driver";

            Class<?> driverClass = Class.forName(
                    driverName,
                    true,
                    DatabaseManager.class.getClassLoader()
            );

            Driver driver = (Driver) driverClass
                    .getDeclaredConstructor()
                    .newInstance();

            Connection newConnection =
                    driver.connect(url, new Properties());

            if (newConnection == null) {
                throw new SQLException(
                        "H2 no aceptó la URL: " + url
                );
            }

            connection = newConnection;
            connection.setAutoCommit(true);

            initializeTables();

            plugin.getLogger().info(
                    "Base de datos H2 abierta correctamente."
            );
            plugin.getLogger().info(
                    "Archivo: "
                            + databaseFile.getAbsolutePath() + ".mv.db"
            );

        } catch (ReflectiveOperationException
                 | ClassCastException
                 | LinkageError exception) {
            close();

            throw new SQLException(
                    "No se pudo cargar el controlador H2 incluido "
                            + "en DeluxeStats.",
                    exception
            );
        } catch (SQLException exception) {
            close();

            throw new SQLException(
                    "No se pudo conectar o inicializar H2.",
                    exception
            );
        }
    }

    private void initializeTables() throws SQLException {
        try (Statement statement = connection.createStatement()) {

            // Estadísticas históricas. No se reinician.
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS player_stats ("
                            + "uuid VARCHAR(36) PRIMARY KEY,"
                            + "name VARCHAR(64) NOT NULL,"
                            + "kills INTEGER NOT NULL DEFAULT 0,"
                            + "deaths INTEGER NOT NULL DEFAULT 0,"
                            + "ores_mined INTEGER NOT NULL DEFAULT 0,"
                            + "money_earned DOUBLE PRECISION NOT NULL DEFAULT 0,"
                            + "active_seconds BIGINT NOT NULL DEFAULT 0,"
                            + "current_streak INTEGER NOT NULL DEFAULT 0,"
                            + "best_streak INTEGER NOT NULL DEFAULT 0"
                            + ")"
            );

            // Temporadas.
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS seasons ("
                            + "id INTEGER GENERATED BY DEFAULT AS IDENTITY "
                            + "PRIMARY KEY,"
                            + "start_time BIGINT NOT NULL,"
                            + "end_time BIGINT NOT NULL,"
                            + "status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',"
                            + "closed_at BIGINT"
                            + ")"
            );

            // Estadísticas independientes de cada temporada.
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS season_stats ("
                            + "season_id INTEGER NOT NULL,"
                            + "uuid VARCHAR(36) NOT NULL,"
                            + "kills INTEGER NOT NULL DEFAULT 0,"
                            + "deaths INTEGER NOT NULL DEFAULT 0,"
                            + "ores_mined INTEGER NOT NULL DEFAULT 0,"
                            + "money_earned DOUBLE PRECISION NOT NULL DEFAULT 0,"
                            + "active_seconds BIGINT NOT NULL DEFAULT 0,"
                            + "PRIMARY KEY (season_id, uuid)"
                            + ")"
            );

            // Ganadores registrados al finalizar una temporada.
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS season_winners ("
                            + "season_id INTEGER NOT NULL,"
                            + "category VARCHAR(64) NOT NULL,"
                            + "position INTEGER NOT NULL,"
                            + "uuid VARCHAR(36) NOT NULL,"
                            + "reward DOUBLE PRECISION NOT NULL DEFAULT 0,"
                            + "PRIMARY KEY (season_id, category, position)"
                            + ")"
            );

            /*
             * Tabla heredada. Se conserva para no eliminar datos
             * de versiones anteriores del plugin.
             */
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS reward_claims ("
                            + "season_id INTEGER NOT NULL,"
                            + "category VARCHAR(64) NOT NULL,"
                            + "position INTEGER NOT NULL,"
                            + "uuid VARCHAR(36) NOT NULL,"
                            + "claimed_at BIGINT NOT NULL,"
                            + "PRIMARY KEY (season_id, category, position)"
                            + ")"
            );

            /*
             * Registro nuevo de recompensas.
             * Permite varias recompensas por jugador y categoría.
             * PENDING = pendiente; CLAIMED = entregada.
             */
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS season_rewards ("
                            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY "
                            + "PRIMARY KEY,"
                            + "season_id INTEGER NOT NULL,"
                            + "category VARCHAR(64) NOT NULL,"
                            + "position INTEGER NOT NULL,"
                            + "uuid VARCHAR(36) NOT NULL,"
                            + "reward_type VARCHAR(32) NOT NULL,"
                            + "reward_value DOUBLE PRECISION NOT NULL DEFAULT 0,"
                            + "reward_command VARCHAR(2048),"
                            + "status VARCHAR(16) NOT NULL DEFAULT 'PENDING',"
                            + "created_at BIGINT NOT NULL,"
                            + "claimed_at BIGINT,"
                            + "UNIQUE (season_id, category, position, uuid, "
                            + "reward_type, reward_command)"
                            + ")"
            );

            statement.executeUpdate(
                    "CREATE INDEX IF NOT EXISTS idx_season_rewards_player "
                            + "ON season_rewards (uuid, status)"
            );

            statement.executeUpdate(
                    "CREATE INDEX IF NOT EXISTS idx_season_stats_ranking "
                            + "ON season_stats (season_id, kills, ores_mined, "
                            + "active_seconds)"
            );

            // Control anti-farmeo de kills entre parejas de jugadores.
            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS kill_antifarm_pairs ("
                            + "player_a_uuid VARCHAR(36) NOT NULL,"
                            + "player_b_uuid VARCHAR(36) NOT NULL,"
                            + "last_kill_at BIGINT NOT NULL,"
                            + "PRIMARY KEY (player_a_uuid, player_b_uuid)"
                            + ")"
            );

            statement.executeUpdate(
                    "CREATE TABLE IF NOT EXISTS kill_antifarm_player_targets ("
                            + "killer_uuid VARCHAR(36) NOT NULL,"
                            + "victim_uuid VARCHAR(36) NOT NULL,"
                            + "last_kill_at BIGINT NOT NULL,"
                            + "PRIMARY KEY (killer_uuid, victim_uuid)"
                            + ")"
            );
        }

        plugin.getLogger().info(
                "Tablas y comprobaciones de esquema completadas."
        );
    }

    public synchronized Connection getConnection() {
        return connection;
    }

    public synchronized void close() {
        if (connection != null) {
            try {
                connection.close();
            } catch (SQLException exception) {
                plugin.getLogger().error(
                        "No se pudo cerrar la base de datos H2.",
                        exception
                );
            } finally {
                connection = null;
            }
        }
    }

    private void checkConnection() throws SQLException {
        if (connection == null || connection.isClosed()) {
            throw new SQLException(
                    "La conexión con H2 no está disponible."
            );
        }
    }

    public synchronized void ensurePlayer(Player player)
            throws SQLException {
        ensurePlayer(player.getUniqueId().toString(), player.getName());
    }

    private void ensurePlayer(String uuid, String name)
            throws SQLException {
        checkConnection();

        String updateSql =
                "UPDATE player_stats SET name = ? WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(updateSql)) {
            statement.setString(1, name);
            statement.setString(2, uuid);

            if (statement.executeUpdate() == 0) {
                String insertSql =
                        "INSERT INTO player_stats (uuid, name) VALUES (?, ?)";

                try (PreparedStatement insert =
                             connection.prepareStatement(insertSql)) {
                    insert.setString(1, uuid);
                    insert.setString(2, name);
                    insert.executeUpdate();
                }
            }
        }
    }

    public synchronized void recordOre(Player player)
            throws SQLException {
        ensurePlayer(player);

        String uuid = player.getUniqueId().toString();

        String sql =
                "UPDATE player_stats SET ores_mined = ores_mined + 1 "
                        + "WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setString(1, uuid);
            statement.executeUpdate();
        }

}

    public synchronized void updateMoneyBalance(
            Player player,
            double balance
    ) throws SQLException {
        ensurePlayer(player);

        String sql =
                "UPDATE player_stats SET money_earned = ? WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setDouble(1, balance);
            statement.setString(
                    2, player.getUniqueId().toString()
            );
            statement.executeUpdate();
        }
    }

    public synchronized void addActiveSeconds(
            Player player,
            long seconds
    ) throws SQLException {
        if (seconds <= 0L) {
            return;
        }

        ensurePlayer(player);

        String uuid = player.getUniqueId().toString();

        String sql =
                "UPDATE player_stats "
                        + "SET active_seconds = active_seconds + ? "
                        + "WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setLong(1, seconds);
            statement.setString(2, uuid);
            statement.executeUpdate();
        }

}


}
