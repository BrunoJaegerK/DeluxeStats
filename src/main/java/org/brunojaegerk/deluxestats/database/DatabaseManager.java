    public synchronized void addActiveSeconds(
            Player player,
            long seconds
    ) throws SQLException {
        if (seconds <= 0L) {
            return;
        }

        ensurePlayer(player);

        String uuid = player.getUniqueId().toString();

        String sql =
                "UPDATE player_stats "
                        + "SET active_seconds = active_seconds + ? "
                        + "WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setLong(1, seconds);
            statement.setString(2, uuid);
            statement.executeUpdate();
        }

        Integer seasonId = getActiveSeasonId();
        if (seasonId != null) {
            updateSeasonStat(
                    seasonId, uuid, "active_seconds", seconds
            );
        }
    }

    /**
     * Devuelve la posición de un jugador en una clasificación.
     * Categorías admitidas: kills, ores_mined, active_seconds.
     */
    public synchronized int getSeasonPosition(
            int seasonId,
            String category,
            String uuid
    ) throws SQLException {
        checkConnection();

        if (!"kills".equals(category)
                && !"ores_mined".equals(category)
                && !"active_seconds".equals(category)) {
            throw new SQLException(
                    "Categoría de clasificación no válida."
            );
        }

        String sql =
                "SELECT position FROM ("
                        + "SELECT uuid, ROW_NUMBER() OVER (ORDER BY "
                        + category + " DESC, uuid ASC) AS position "
                        + "FROM season_stats WHERE season_id = ?"
                        + ") ranked WHERE uuid = ?";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setInt(1, seasonId);
            statement.setString(2, uuid);

            try (ResultSet result = statement.executeQuery()) {
                return result.next() ? result.getInt("position") : -1;
            }
        }
    }

    /**
     * Registra al ganador de una categoría y posición.
     * La clave única impide duplicar el ganador de la misma posición.
     */
    public synchronized void saveSeasonWinner(
            int seasonId,
            String category,
            int position,
            String uuid,
            double reward
    ) throws SQLException {
        checkConnection();

        String sql =
                "MERGE INTO season_winners "
                        + "(season_id, category, position, uuid, reward) "
                        + "KEY (season_id, category, position) "
                        + "VALUES (?, ?, ?, ?, ?)";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setInt(1, seasonId);
            statement.setString(2, category);
            statement.setInt(3, position);
            statement.setString(4, uuid);
            statement.setDouble(5, reward);
            statement.executeUpdate();
        }
    }

    /**
     * Registra una recompensa pendiente de entrega.
     * rewardType puede ser MONEY o COMMAND.
     */
    public synchronized long createSeasonReward(
            int seasonId,
            String category,
            int position,
            String uuid,
            String rewardType,
            double rewardValue,
            String rewardCommand
    ) throws SQLException {
        checkConnection();

        String sql =
                "INSERT INTO season_rewards "
                        + "(season_id, category, position, uuid, "
                        + "reward_type, reward_value, reward_command, "
                        + "status, created_at) "
                        + "SELECT ?, ?, ?, ?, ?, ?, ?, 'PENDING', ? "
                        + "WHERE NOT EXISTS ("
                        + "SELECT 1 FROM season_rewards "
                        + "WHERE season_id = ? AND category = ? "
                        + "AND position = ? AND uuid = ? "
                        + "AND reward_type = ? "
                        + "AND reward_command IS NOT DISTINCT FROM ?"
                        + ")";

        try (PreparedStatement statement = connection.prepareStatement(
                sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setInt(1, seasonId);
            statement.setString(2, category);
            statement.setInt(3, position);
            statement.setString(4, uuid);
            statement.setString(5, rewardType);
            statement.setDouble(6, rewardValue);
            statement.setString(7, rewardCommand);
            statement.setLong(8, System.currentTimeMillis());

            statement.setInt(9, seasonId);
            statement.setString(10, category);
            statement.setInt(11, position);
            statement.setString(12, uuid);
            statement.setString(13, rewardType);
            statement.setString(14, rewardCommand);

            int inserted = statement.executeUpdate();

            if (inserted == 0) {
                return -1L;
            }

            try (ResultSet keys = statement.getGeneratedKeys()) {
                return keys.next() ? keys.getLong(1) : -1L;
            }
        }
    }

    /**
     * Marca como entregada una recompensa pendiente.
     */
    public synchronized boolean claimSeasonReward(long rewardId)
            throws SQLException {
        checkConnection();

        String sql =
                "UPDATE season_rewards SET "
                        + "status = 'CLAIMED', claimed_at = ? "
                        + "WHERE id = ? AND status = 'PENDING'";

        try (PreparedStatement statement =
                     connection.prepareStatement(sql)) {
            statement.setLong(1, System.currentTimeMillis());
            statement.setLong(2, rewardId);

            return statement.executeUpdate() == 1;
        }
    }

